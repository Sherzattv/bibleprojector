/** Ключ поиска книги: без регистра, пробелов и дефисов («1-е Кор» → «1екор») */
function bookKey(input: string): string {
  return input.toLowerCase().replace(/\s+/g, '').replace(/-/g, '')
}

/**
 * Сокращение → код. Приоритет при совпадениях: явные сокращения, затем
 * короткие нативные, затем отображаемые имена — чтобы показанную на экране
 * ссылку («Екклесиаст», «От Матфея») можно было ввести обратно.
 */
const CODE_BY_KEY: ReadonlyMap<string, string> = (() => {
  const map = new Map<string, string>()
  const claim = (key: string, code: string) => {
    if (key && !map.has(key)) map.set(key, code)
  }
  for (const b of BOOKS) for (const abbr of b.abbr) map.set(abbr, b.code)
  for (const b of BOOKS) {
    for (const abbr of EXTRA_ABBR[b.code] ?? []) claim(abbr, b.code)
    for (const name of [b.ru, b.kz, b.ky]) claim(bookKey(name), b.code)
  }
  return map
})()

/** Код книги по вводу оператора: «ин», «римлянам», «1 кор», «жар» */
export function getCanonicalCode(input: string): string | null {
  return CODE_BY_KEY.get(bookKey(input)) ?? null
}
