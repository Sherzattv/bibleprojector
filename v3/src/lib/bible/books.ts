const BOOK_BY_CODE = new Map(BOOKS.map((b) => [b.code, b]))

export function findBookInfo(code: string): BookInfo | null {
  return BOOK_BY_CODE.get(code) ?? null
}

// ── BookId переводов ───────────────────────────────────

const CANONICAL_ORDER = BOOKS.map((b) => b.code)

/**
 * В файле KTB соборные послания (JAS–JUD) стоят перед посланиями Павла
 * (ROM–HEB); остальные книги — на своих местах
 */
const KTB_ORDER = (() => {
  const at = (code: string) => CANONICAL_ORDER.indexOf(code)
  const pauline = CANONICAL_ORDER.slice(at('ROM'), at('HEB') + 1)
  const general = CANONICAL_ORDER.slice(at('JAS'), at('JUD') + 1)
  return [...CANONICAL_ORDER.slice(0, at('ROM')), ...general, ...pauline, 'REV']
})()

/** BookId в файле перевода = позиция книги в его порядке, с единицы */
function bookIds(order: readonly string[]): ReadonlyMap<string, number> {
  return new Map(order.map((code, i) => [code, i + 1]))
}

const STANDARD_IDS = bookIds(CANONICAL_ORDER)

const BOOK_IDS: Readonly<Record<string, ReadonlyMap<string, number>>> = {
  RST: STANDARD_IDS,
  NRT: STANDARD_IDS,
  KTB: bookIds(KTB_ORDER),
  KYB: STANDARD_IDS,
}

/** Обратные карты BookId → код: результаты поиска приходят с BookId */
const CODES_BY_ID: Readonly<Record<string, ReadonlyMap<number, string>>> = Object.fromEntries(
  Object.entries(BOOK_IDS).map(([translation, ids]) => [
    translation,
    new Map([...ids].map(([code, id]) => [id, code])),
  ]),
)

/** BookId книги в файле перевода; null — перевод или книга неизвестны */
export function getBookId(code: string, translation: string): number | null {
  return BOOK_IDS[translation]?.get(code) ?? null
}

/** Канонический код по BookId перевода */
export function codeForBookId(translation: string, bookId: number): string | null {
  return CODES_BY_ID[translation]?.get(bookId) ?? null
}

// ── Названия ───────────────────────────────────────────

/** Язык названий книг для перевода */
export function bookLanguage(translation: string): BookLanguage {
  if (translation === 'KTB') return 'kz'
  if (translation === 'KYB') return 'ky'
  return 'ru'
}

/** Название книги на языке; неизвестный код — «Библия» */
export function getBookTitle(code: string, lang: BookLanguage = 'ru'): string {
  const info = BOOK_BY_CODE.get(code)
  if (!info) return 'Библия'
  return info[lang] || info.ru
}

/** Название книги так, как его пишет сам перевод */
export function bookTitleIn(code: string, translation: string): string {
  return getBookTitle(code, bookLanguage(translation))
}

